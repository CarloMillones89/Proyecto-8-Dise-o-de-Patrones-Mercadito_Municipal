private void cargarStock() {

        modelo.setRowCount(0);

        List<Producto> productos = controller.consultarStock();

        for (Producto p : productos) {

            Object[] fila = {
                p.getIdProducto(),
                p.getCodigoBarras(),
                p.getNombre(),
                p.getPrecioVenta(),
                p.getStockActual(),
                p.getCategoria()
            };

            modelo.addRow(fila);
        }
    }

    // BUSCAR PRODUCTO POR NOMBRE
    private void buscarStock() {

        String nombre = jTextField1.getText().trim();

        if (nombre.isEmpty()) {
            cargarStock();
            return;
        }

        modelo.setRowCount(0);

        List<Producto> productos = controller.buscarStock(nombre);

        for (Producto p : productos) {

            Object[] fila = {
                p.getIdProducto(),
                p.getCodigoBarras(),
                p.getNombre(),
                p.getPrecioVenta(),
                p.getStockActual(),
                p.getCategoria()
            };

            modelo.addRow(fila);
        }

        if (productos.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "No se encontraron productos con ese nombre."
            );
        }
    }
